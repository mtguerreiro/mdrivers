#include "pwm_irq_handler.h"

/* Device and drivers */
#include <stdio.h>
#include "pico/stdlib.h"

#include "hardware/irq.h"
#include "hardware/pwm.h"

#define PWM_IRQ_HANDLER_DBG 1

#define PWM_IRQ_HANDLER_DBG_PIN 3

#if (PWM_IRQ_HANDLER_DBG == 1)
#include "hardware/gpio.h"
#endif
//===========================================================================

//===========================================================================
/*-------------------------------- Defines --------------------------------*/
//===========================================================================


//===========================================================================

//===========================================================================
/*--------------------------------- Enums ---------------------------------*/
//===========================================================================

//===========================================================================

//===========================================================================
/*-------------------------------- Structs --------------------------------*/
//===========================================================================
pwmIrqHandle_t irqhandles[8] = {0};
//===========================================================================

//===========================================================================
/*-------------------------------- Globals --------------------------------*/
//===========================================================================

//===========================================================================

//===========================================================================
/*------------------------------- Prototypes ------------------------------*/
//===========================================================================
//---------------------------------------------------------------------------
static void pwmIrqHandler(void);
//---------------------------------------------------------------------------
//===========================================================================

//===========================================================================
/*------------------------------- Functions -------------------------------*/
//===========================================================================
//---------------------------------------------------------------------------
void pwmIrqHandlerInitialize(uint8_t prio){

    irq_set_exclusive_handler(PWM_IRQ_WRAP, pwmIrqHandler);
    irq_set_priority(PWM_IRQ_WRAP, prio);
    irq_set_enabled(PWM_IRQ_WRAP, true);

#if (PWM_IRQ_HANDLER_DBG == 1)
    gpio_init(PWM_IRQ_HANDLER_DBG_PIN);
    gpio_set_dir(PWM_IRQ_HANDLER_DBG_PIN, GPIO_OUT);
    gpio_put(PWM_IRQ_HANDLER_DBG_PIN, 0);
#endif
}
//---------------------------------------------------------------------------
void pwmIrqHandlerSliceEnable(unsigned int slice){

    pwm_clear_irq(slice);
    pwm_set_irq_enabled(slice, true);
}
//---------------------------------------------------------------------------
void pwmIrqHandlerSliceDisable(unsigned int slice){

    pwm_set_irq_enabled(slice, false);
}
//---------------------------------------------------------------------------
int32_t pwmIrqHandlerAdd(unsigned int  slice, pwmIrqHandle_t handle){

    if( slice >= 8 ) return -1;

    irqhandles[slice] = handle;

    return 0;
}
//---------------------------------------------------------------------------
//===========================================================================


//===========================================================================
/*--------------------------- Static functions ----------------------------*/
//===========================================================================
//---------------------------------------------------------------------------

//---------------------------------------------------------------------------
//===========================================================================

//===========================================================================
/*-----------------------------  IRQ Handlers -----------------------------*/
//===========================================================================
//---------------------------------------------------------------------------
static void pwmIrqHandler(void){

    uint32_t status;
    uint32_t k;

#if (PWM_IRQ_HANDLER_DBG == 1)
    gpio_put(PWM_IRQ_HANDLER_DBG_PIN, 1);
#endif

    status = pwm_get_irq_status_mask();

    for(k = 0; k < 8; k++){
        if( !(status  & (1U << k)) ) continue;

        pwm_clear_irq(k);
        if( irqhandles[k] ) irqhandles[k]();
    }

#if (PWM_IRQ_HANDLER_DBG == 1)
    gpio_put(PWM_IRQ_HANDLER_DBG_PIN, 0);
#endif
}
