#include "onewirehl.h"

/* Device and drivers */
#include <stdio.h>
#include "pico/stdlib.h"
#include "hardware/pio.h"

#include "mhw/pico/onewire/onewire.h"
//===========================================================================

//===========================================================================
/*-------------------------------- Globals --------------------------------*/
//===========================================================================
OW ow;
//===========================================================================

//===========================================================================
/*------------------------------- Functions -------------------------------*/
//===========================================================================
//---------------------------------------------------------------------------
int32_t onewirehlInitialize(void *gpio, uint8_t pin){

    (void)gpio;

    PIO pio = pio1;
    uint offset;
    int status;

    offset = pio_add_program (pio, &onewire_program);

    status = ow_init(&ow, pio, offset, pin);

    return status;
}
//---------------------------------------------------------------------------
int32_t onewirehlReset(uint32_t to){

    (void)to;
    bool status;

    status = ow_reset(&ow);

    if( status == false) return -1;

    return 0;
}
//---------------------------------------------------------------------------
int32_t onewirehlWrite(uint8_t *data, uint16_t size, uint32_t to){

    (void)to;

    while(size--) ow_send(&ow, *data++);

    return 0;
}
//---------------------------------------------------------------------------
int32_t onewirehlRead(uint8_t *data, uint16_t size, uint32_t to){

    (void)to;

    while(size--) *data++ = ow_read (&ow);

    return 0;
}
