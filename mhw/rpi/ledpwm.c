
//=============================================================================
/*-------------------------------- Includes ---------------------------------*/
//=============================================================================
#include "ledpwm.h"

#include "pigpio.h"
//=============================================================================

//=============================================================================
/*------------------------------- Definitions -------------------------------*/
//=============================================================================
#define LED_PWM_CONFIG_PWM_PIN          18
#define LED_PWM_CONFIG_PWM_FREQ         50000
//=============================================================================

//=============================================================================
/*--------------------------------- Globals ---------------------------------*/
//=============================================================================

//=============================================================================

//=============================================================================
/*-------------------------------- Prototypes -------------------------------*/
//=============================================================================
static int32_t ledpwmInitializeHw(void);

//=============================================================================

//=============================================================================
/*-------------------------------- Functions --------------------------------*/
//=============================================================================
//-----------------------------------------------------------------------------
int32_t ledpwmInitialize(void){

    if( ledpwmInitializeHw() != 0 ) return -1;

    return 0;
}
//-----------------------------------------------------------------------------
int32_t ledpwmSetIntensity(void *p, uint8_t intensity){

    (void) p;

    gpioPWM(LED_PWM_CONFIG_PWM_PIN, intensity);

    return 0;
}
//-----------------------------------------------------------------------------
//=============================================================================

//=============================================================================
/*---------------------------- Static functions -----------------------------*/
//=============================================================================
//-----------------------------------------------------------------------------
static int32_t ledpwmInitializeHw(void){

    if( gpioInitialise() < 0 ) return -1;

    gpioSetMode(LED_PWM_CONFIG_PWM_PIN, PI_OUTPUT);
    gpioSetPWMrange(LED_PWM_CONFIG_PWM_PIN, 100);
    gpioSetPWMfrequency(LED_PWM_CONFIG_PWM_PIN, LED_PWM_CONFIG_PWM_FREQ);
    gpioPWM(LED_PWM_CONFIG_PWM_PIN, 0);

    return 0;
}
